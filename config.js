//  거치느라 "잠깐 기다림"이 생기는데, 처음부터 기다리는 방식으로
//  짜두면 화면 코드를 안 고쳐도 됩니다.
// ============================================================

// ---- Supabase 연결 ----------------------------------------
// config.js 의 값으로 창고와 연결하는 객체(db)를 만듭니다.
let db = null;
const 연결됨 = SUPABASE_URL && SUPABASE_ANON_KEY;

if (연결됨) {
  db = supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
} else {
  // 키를 아직 안 넣은 상태. 화면이 깨지지 않게 안내만 띄웁니다.
  console.warn("[db.js] Supabase 키가 아직 없습니다. config.js 를 채우면 연결됩니다.");
}

// ============================================================
//  고객사 (customers)
// ============================================================

// 고객 목록 전체를 가져온다.
async function 고객목록가져오기() {
  if (!연결됨) return [];                 // 키 없으면 빈 목록(화면 안 깨짐)
  const { data, error } = await db
    .from("customers")
    .select("*")
    .order("created_at", { ascending: false });
  if (error) { console.error("고객목록가져오기 실패:", error); return []; }
  return data;
}

// 고객 한 명을 추가한다.
async function 고객추가하기(고객정보) {
  if (!연결됨) return null;
  const { data, error } = await db
    .from("customers")
    .insert(고객정보)
    .select();
  if (error) { console.error("고객추가하기 실패:", error); return null; }
  return data;
}

